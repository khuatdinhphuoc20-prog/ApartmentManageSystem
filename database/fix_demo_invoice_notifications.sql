BEGIN TRY
    BEGIN TRANSACTION;

    UPDATE notification
    SET title = repair.title,
        body = repair.body,
        updated_at = SYSUTCDATETIME()
    FROM dbo.notifications AS notification
    INNER JOIN @repairs AS repair
        ON repair.event_key = notification.event_key
        AND repair.invoice_id = notification.invoice_id
    WHERE notification.source_type = 'SYSTEM';

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;

